def create_loan(db: Session, data: schemas.LoanCreate):
    obj = models.Loan(
        **data.model_dump(),
        status="Pending",
    )
    db.add(obj); db.commit(); db.refresh(obj)
    return obj

def get_loans(db: Session):
    return db.query(models.Loan).all()

def get_loan(db: Session, loan_id: int):
    return db.query(models.Loan).filter(
        models.Loan.loan_id == loan_id
    ).first()

def update_loan(db: Session, loan_id: int, data: schemas.LoanUpdate):
    from fastapi import HTTPException
    obj = get_loan(db, loan_id)
    if not obj: return None
    updates = data.model_dump(exclude_unset=True)
    if "loan_amount" in updates and obj.status in ("ACTIVE", "CLOSED"):
        raise HTTPException(
            status_code=400,
            detail=f"Cannot change loan_amount on a loan with status '{obj.status}'. "
                   "The installment schedule is already generated and would become inconsistent.",
        )
    for k, v in updates.items():
        setattr(obj, k, v)
    db.commit(); db.refresh(obj)
    return obj

def delete_loan(db: Session, loan_id: int):
    obj = get_loan(db, loan_id)
    if not obj: return None
    db.delete(obj); db.commit()
    return obj


