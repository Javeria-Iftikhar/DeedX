def get_currency(db: Session, currency_code: str):
    return db.query(models.Currency).filter(
        models.Currency.currency_code == currency_code
    ).first()

def delete_currency(db: Session, currency_code: str):
    obj = get_currency(db, currency_code)
    if not obj: return None
    db.delete(obj); db.commit()
    return obj


def update_currency_patch(db: Session, currency_code: str, currency_name=None, symbol=None, exchange_regime=None):
    obj = get_currency(db, currency_code)
    if not obj:
        return None
    if currency_name is not None:
        obj.currency_name = currency_name
    if symbol is not None:
        obj.symbol = symbol
    if exchange_regime is not None:
        obj.exchange_regime = exchange_regime
    db.commit()
    db.refresh(obj)
    return obj


def rename_currency_code(
    db: Session,
    old_code: str,
    new_code: str,
    *,
    currency_name=None,
    symbol=None,
    exchange_regime=None,
):
    """
    Change currency primary key and propagate FK updates to dependent tables.
    """
    from fastapi import HTTPException

    old_code = str(old_code).strip().upper()
    new_code = str(new_code).strip().upper()
    obj = get_currency(db, old_code)
    if not obj:
        return None
    if old_code == new_code:
        return update_currency_patch(db, old_code, currency_name, symbol, exchange_regime)

    if get_currency(db, new_code):
        raise HTTPException(
            status_code=400,
            detail=f"Currency code '{new_code}' already exists. Choose a different code.",
        )

    final_name = currency_name if currency_name is not None else obj.currency_name
    final_symbol = symbol if symbol is not None else obj.symbol
    final_regime = exchange_regime if exchange_regime is not None else obj.exchange_regime

    db.query(models.Country).filter(models.Country.currency_code == old_code).update(
        {models.Country.currency_code: new_code}, synchronize_session=False
    )
    db.query(models.Loan).filter(models.Loan.currency_code == old_code).update(
        {models.Loan.currency_code: new_code}, synchronize_session=False
    )
    db.query(models.ExchangeRate).filter(models.ExchangeRate.from_currency == old_code).update(
        {models.ExchangeRate.from_currency: new_code}, synchronize_session=False
    )
    db.query(models.ExchangeRate).filter(models.ExchangeRate.to_currency == old_code).update(
        {models.ExchangeRate.to_currency: new_code}, synchronize_session=False
    )
    db.query(models.FinancialTransaction).filter(
        models.FinancialTransaction.currency_code == old_code
    ).update({models.FinancialTransaction.currency_code: new_code}, synchronize_session=False)

    db.delete(obj)
    db.flush()
    new_obj = models.Currency(
        currency_code=new_code,
        currency_name=final_name,
        symbol=final_symbol,
        exchange_regime=final_regime,
    )
    db.add(new_obj)
    db.commit()
    db.refresh(new_obj)
    return new_obj


