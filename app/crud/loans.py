"""
crud/loans.py  —  CRUD for:
  Currency, Country, LoanProgram, IMFAccount,
  Loan, LoanCondition, LoanConditionMapping,
  LoanDisbursement, Repayment, Installment

HYBRID MODEL RULE
─────────────────
  Simple entity CRUD lives here as thin DB operations.
  Financial actions (repayment, disbursement) are DELEGATED to
  financial_service — they handle atomicity, installment scheduling,
  transaction generation, and audit logging.

NAMING FIX
──────────
  adjust_imf_account_balance() — the correct function name used here
  and in the router. (Was inconsistently named in previous version.)

INSTALLMENT NOTE
────────────────
  Installments are auto-generated by financial_service on first
  disbursement. There is no create_installment() here — only reads.
  The crud has no repayment_no-based installment queries because the
  Installment model has no repayment_no column.
"""

